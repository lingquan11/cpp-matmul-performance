#include <iostream>                       // 引入输入输出功能
using namespace std;                      // 允许直接使用 cout

int main() {                              // 定义程序入口
    int A[2][2] = { { 2, 1 },{ 3, 4 } };       // 定义左矩阵 A
    int B[2][2] = { { 5, 2 },{ 1, 6 } };       // 定义右矩阵 B
    int C[2][2] = {};                     // 定义结果矩阵 C，并初始化为 0

    for (int i = 0; i < 2; ++i) {         // 遍历结果矩阵的每一行
        for (int j = 0; j < 2; ++j) {     // 遍历结果矩阵的每一列
            C[i][j] = 0;                 // 开始计算当前元素前，将累加值清零

            for (int k = 0; k < 2; ++k) { // 遍历对应元素的配对位置
                C[i][j] += A[i][k] * B[k][j];// TODO 1：将 A 和 B 的对应元素相乘，并累加到 C[i][j]
            }                             // 结束当前输出元素的累加
        }                                 // 结束当前行的列遍历
    }                                     // 结束所有行的遍历

    for (int i = 0;i < 2;++i) {
        for (int j = 0;j < 2;++j) {
            cout << C[i][j] << " ";// TODO 2：使用两重循环打印结果矩阵 C
        }
        cout << endl;
    }
    return 0;                             // 返回 0，表示程序正常结束
}                                         // 结束 main 函数
